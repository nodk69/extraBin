export const GENERATED_MARKER =
  "<!-- Generated by scripts/engineering/sync-opencode-agents.mjs from .agents/agents/%NAME%.md. Do not edit by hand. -->";

function stripQuotes(value) {
  const text = String(value ?? "").trim();
  if (
    (text.startsWith('"') && text.endsWith('"')) ||
    (text.startsWith("'") && text.endsWith("'"))
  ) {
    return text.slice(1, -1);
  }
  return text;
}

/** Minimal parser for the flat YAML frontmatter used by the canonical agents. */
export function parseFrontmatter(text) {
  const normalized = text.replace(/\r\n/g, "\n").replace(/^\uFEFF/, "");
  if (!normalized.startsWith("---\n")) {
    throw new Error('missing YAML frontmatter (file must start with "---")');
  }
  const end = normalized.indexOf("\n---", 4);
  if (end === -1) throw new Error('frontmatter is not closed with "---"');

  const header = normalized.slice(4, end);
  const body = normalized.slice(end + 4).replace(/^\n/, "");
  const data = {};

  for (const rawLine of header.split("\n")) {
    if (!rawLine.trim() || rawLine.trim().startsWith("#")) continue;
    const keyMatch = rawLine.match(/^([A-Za-z0-9_-]+):\s*(.*)$/);
    if (!keyMatch) continue;
    const [, key, rawValue] = keyMatch;
    data[key] = rawValue.trim() ? stripQuotes(rawValue) : "";
  }

  return { data, body };
}

export function canonicalAgentPath(root, name) {
  return join(root, ".agents", "agents", `${name}.md`);
}

export function openCodeAgentPath(root, name) {
  return join(root, ".opencode", "agents", `${name}.md`);
}

export function readCanonicalAgent(root, name) {
  const file = canonicalAgentPath(root, name);
  if (!existsSync(file)) return null;
  const { data } = parseFrontmatter(readFileSync(file, "utf8"));
  return { name: data.name, description: data.description };
}

export function listCanonicalAgentNames(root) {
  const dir = join(root, ".agents", "agents");
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((entry) => entry.endsWith(".md"))
    .map((entry) => entry.replace(/\.md$/, ""))
    .sort();
}

export function renderOpenCodeAgent({ name, description }) {
  const permissions = ADAPTER_PERMISSIONS.map(
    (rule) =>
      `  - action: ${rule.action}\n    resource: ${JSON.stringify(rule.resource)}\n    effect: ${rule.effect}`
  ).join("\n");

  return `---
description: ${JSON.stringify(description)}
mode: subagent
permissions:
${permissions}
---

${GENERATED_MARKER.replace("%NAME%", name)}

# ${name}

You are the \`${name}\` specialist for the ExtraBin repository, running as an OpenCode subagent.

Your authoritative role definition is \`.agents/agents/${name}.md\`. Read it first with the \`read\` tool and follow it exactly: mission, activation, scope and boundaries, review checklist, evidence standard, output contract and blocking rules.

Non-negotiable rules for this subagent:

- Read-only review. Never edit application code, tests, configuration or documentation. The file-edit tools are denied to you; do not use shell commands to write or revert files either. Report findings; the primary agent applies fixes.
- Never print secret values from \`.env\`, cookie jars, private keys or credentials. Report the file and variable name only.
- Cite exact \`file:line\` evidence for every finding and separate **Confirmed** from **Potential**.
- Report the commands you actually executed with their exit codes. Never claim a check passed without its output.
- Do not silently approve work outside your expertise. Say what you did not test.
`;
}
