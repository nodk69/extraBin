-- 1. ADD VIEWS COUNTER TO PASTES TABLE
ALTER TABLE pastes ADD COLUMN views BIGINT NOT NULL DEFAULT 0;

-- 2. CREATE PASTE_COMMENTS TABLE
CREATE TABLE paste_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paste_id BIGINT NOT NULL REFERENCES pastes(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    author_name VARCHAR(50) NOT NULL,
    content VARCHAR(2000) NOT NULL,
    deletion_capability_hash VARCHAR(128),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_paste_comments_paste_created ON paste_comments (paste_id, created_at ASC);
CREATE INDEX idx_paste_comments_user ON paste_comments (user_id);
