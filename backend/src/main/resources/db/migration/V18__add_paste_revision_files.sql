-- 1. CREATE PASTE_REVISION_FILES TABLE
-- Captures the exact workspace files snapshot for each historical paste revision.
CREATE TABLE paste_revision_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    revision_id BIGINT NOT NULL REFERENCES paste_revisions(id) ON DELETE CASCADE,
    filename VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    language VARCHAR(50) NOT NULL DEFAULT 'plaintext',
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_paste_revision_filename UNIQUE (revision_id, filename),
    CONSTRAINT chk_paste_revision_file_order CHECK (sort_order >= 0)
);

CREATE INDEX idx_paste_revision_files_rev_order ON paste_revision_files (revision_id, sort_order);

-- 2. BACKFILL EXISTING SINGLE-FILE REVISIONS
-- Ensure all historical single-file revisions remain fully readable and have a corresponding revision file.
INSERT INTO paste_revision_files (revision_id, filename, content, language, sort_order, created_at)
SELECT 
    pr.id,
    CASE 
        WHEN pr.title IS NOT NULL AND TRIM(pr.title) <> '' THEN
            REGEXP_REPLACE(TRIM(pr.title), '[^a-zA-Z0-9._-]', '_') ||
            CASE 
                WHEN TRIM(pr.title) LIKE '%.%' THEN ''
                WHEN pr.language = 'java' THEN '.java'
                WHEN pr.language IN ('javascript', 'js') THEN '.js'
                WHEN pr.language IN ('typescript', 'ts') THEN '.ts'
                WHEN pr.language IN ('python', 'py') THEN '.py'
                WHEN pr.language = 'html' THEN '.html'
                WHEN pr.language = 'css' THEN '.css'
                WHEN pr.language = 'json' THEN '.json'
                WHEN pr.language = 'sql' THEN '.sql'
                WHEN pr.language IN ('markdown', 'md') THEN '.md'
                WHEN pr.language = 'rust' THEN '.rs'
                WHEN pr.language = 'go' THEN '.go'
                WHEN pr.language = 'c' THEN '.c'
                WHEN pr.language = 'cpp' THEN '.cpp'
                WHEN pr.language IN ('csharp', 'cs') THEN '.cs'
                WHEN pr.language = 'php' THEN '.php'
                WHEN pr.language = 'ruby' THEN '.rb'
                WHEN pr.language IN ('yaml', 'yml') THEN '.yaml'
                WHEN pr.language = 'xml' THEN '.xml'
                WHEN pr.language IN ('bash', 'sh') THEN '.sh'
                ELSE '.txt'
            END
        ELSE
            'paste-v' || pr.version ||
            CASE 
                WHEN pr.language = 'java' THEN '.java'
                WHEN pr.language IN ('javascript', 'js') THEN '.js'
                WHEN pr.language IN ('typescript', 'ts') THEN '.ts'
                WHEN pr.language IN ('python', 'py') THEN '.py'
                WHEN pr.language = 'html' THEN '.html'
                WHEN pr.language = 'css' THEN '.css'
                WHEN pr.language = 'json' THEN '.json'
                WHEN pr.language = 'sql' THEN '.sql'
                WHEN pr.language IN ('markdown', 'md') THEN '.md'
                WHEN pr.language = 'rust' THEN '.rs'
                WHEN pr.language = 'go' THEN '.go'
                WHEN pr.language = 'c' THEN '.c'
                WHEN pr.language = 'cpp' THEN '.cpp'
                WHEN pr.language IN ('csharp', 'cs') THEN '.cs'
                WHEN pr.language = 'php' THEN '.php'
                WHEN pr.language = 'ruby' THEN '.rb'
                WHEN pr.language IN ('yaml', 'yml') THEN '.yaml'
                WHEN pr.language = 'xml' THEN '.xml'
                WHEN pr.language IN ('bash', 'sh') THEN '.sh'
                ELSE '.txt'
            END
    END,
    pr.content,
    COALESCE(pr.language, 'plaintext'),
    0,
    pr.created_at
FROM paste_revisions pr;
