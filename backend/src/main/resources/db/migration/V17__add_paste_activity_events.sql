-- 1. PASTE_ACTIVITY_EVENTS TABLE
-- Captures discrete engagement events (VIEW, STAR, UPVOTE) with strict XOR identity
-- (user_id XOR client_ip_hash) and deduplication window.
-- Privacy invariant: never stores raw client IP or paste content.
CREATE TABLE paste_activity_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paste_id BIGINT NOT NULL REFERENCES pastes(id) ON DELETE CASCADE,
    event_type VARCHAR(20) NOT NULL, -- 'VIEW', 'STAR', 'UPVOTE'
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    client_ip_hash VARCHAR(64),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_activity_event_type CHECK (event_type IN ('VIEW', 'STAR', 'UPVOTE')),
    CONSTRAINT chk_activity_event_identity_xor CHECK (
        (user_id IS NOT NULL AND client_ip_hash IS NULL) OR
        (user_id IS NULL AND client_ip_hash IS NOT NULL)
    )
);

-- Index for windowed aggregation joined on paste eligibility
CREATE INDEX idx_activity_events_paste_window ON paste_activity_events (paste_id, created_at DESC);

-- Index for background rolling purge of events older than 30 days
CREATE INDEX idx_activity_events_created_at ON paste_activity_events (created_at);

-- Composite indexes for deduplicating repeated client views within sliding windows
CREATE INDEX idx_activity_events_user_dedup ON paste_activity_events (paste_id, user_id, event_type, created_at DESC);
CREATE INDEX idx_activity_events_ip_dedup ON paste_activity_events (paste_id, client_ip_hash, event_type, created_at DESC);
