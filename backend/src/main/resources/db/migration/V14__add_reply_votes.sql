-- V14__add_reply_votes.sql: Add voting support to threaded replies
-- =========================================================================

-- 1. ADD CACHED COUNTERS TO REPLIES TABLE
ALTER TABLE replies ADD COLUMN upvotes BIGINT NOT NULL DEFAULT 0;
ALTER TABLE replies ADD COLUMN downvotes BIGINT NOT NULL DEFAULT 0;

ALTER TABLE replies ADD CONSTRAINT chk_replies_upvotes_nonneg CHECK (upvotes >= 0);
ALTER TABLE replies ADD CONSTRAINT chk_replies_downvotes_nonneg CHECK (downvotes >= 0);

-- 2. CREATE REPLY_VOTES TABLE WITH STRICT XOR IDENTITY CONSTRAINT
CREATE TABLE reply_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reply_id BIGINT NOT NULL REFERENCES replies(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    client_ip_hash VARCHAR(64),
    vote_type VARCHAR(10) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_reply_vote_type CHECK (vote_type IN ('UP', 'DOWN')),
    CONSTRAINT chk_reply_vote_identity_xor CHECK (
        (user_id IS NOT NULL AND client_ip_hash IS NULL) OR
        (user_id IS NULL AND client_ip_hash IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_reply_votes_user ON reply_votes (reply_id, user_id);
CREATE UNIQUE INDEX uq_reply_votes_ip ON reply_votes (reply_id, client_ip_hash);
CREATE INDEX idx_reply_votes_reply ON reply_votes (reply_id);
