-- 1. CREATE PASTE_FILES TABLE
CREATE TABLE paste_files (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paste_id BIGINT NOT NULL REFERENCES pastes(id) ON DELETE CASCADE,
    filename VARCHAR(255) NOT NULL,
    content TEXT NOT NULL,
    language VARCHAR(50) NOT NULL DEFAULT 'plaintext',
    sort_order INTEGER NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_paste_filename UNIQUE (paste_id, filename),
    CONSTRAINT chk_paste_file_order CHECK (sort_order >= 0)
);

CREATE INDEX idx_paste_files_paste_order ON paste_files (paste_id, sort_order);

-- 2. MIGRATE EXISTING SINGLE-FILE PASTES INTO PASTE_FILES
INSERT INTO paste_files (paste_id, filename, content, language, sort_order, created_at)
SELECT 
    id, 
    CASE 
        WHEN title IS NOT NULL AND TRIM(title) <> '' THEN
            REGEXP_REPLACE(TRIM(title), '[^a-zA-Z0-9._-]', '_') ||
            CASE 
                WHEN TRIM(title) LIKE '%.%' THEN ''
                WHEN language = 'java' THEN '.java'
                WHEN language IN ('javascript', 'js') THEN '.js'
                WHEN language IN ('typescript', 'ts') THEN '.ts'
                WHEN language IN ('python', 'py') THEN '.py'
                WHEN language = 'html' THEN '.html'
                WHEN language = 'css' THEN '.css'
                WHEN language = 'json' THEN '.json'
                WHEN language = 'sql' THEN '.sql'
                WHEN language IN ('markdown', 'md') THEN '.md'
                WHEN language = 'rust' THEN '.rs'
                WHEN language = 'go' THEN '.go'
                WHEN language = 'c' THEN '.c'
                WHEN language = 'cpp' THEN '.cpp'
                WHEN language IN ('csharp', 'cs') THEN '.cs'
                WHEN language = 'php' THEN '.php'
                WHEN language = 'ruby' THEN '.rb'
                WHEN language IN ('yaml', 'yml') THEN '.yaml'
                WHEN language = 'xml' THEN '.xml'
                WHEN language IN ('bash', 'sh') THEN '.sh'
                ELSE '.txt'
            END
        ELSE
            'paste-' || public_id ||
            CASE 
                WHEN language = 'java' THEN '.java'
                WHEN language IN ('javascript', 'js') THEN '.js'
                WHEN language IN ('typescript', 'ts') THEN '.ts'
                WHEN language IN ('python', 'py') THEN '.py'
                WHEN language = 'html' THEN '.html'
                WHEN language = 'css' THEN '.css'
                WHEN language = 'json' THEN '.json'
                WHEN language = 'sql' THEN '.sql'
                WHEN language IN ('markdown', 'md') THEN '.md'
                WHEN language = 'rust' THEN '.rs'
                WHEN language = 'go' THEN '.go'
                WHEN language = 'c' THEN '.c'
                WHEN language = 'cpp' THEN '.cpp'
                WHEN language IN ('csharp', 'cs') THEN '.cs'
                WHEN language = 'php' THEN '.php'
                WHEN language = 'ruby' THEN '.rb'
                WHEN language IN ('yaml', 'yml') THEN '.yaml'
                WHEN language = 'xml' THEN '.xml'
                WHEN language IN ('bash', 'sh') THEN '.sh'
                ELSE '.txt'
            END
    END,
    content, 
    COALESCE(language, 'plaintext'), 
    0, 
    created_at
FROM pastes;
