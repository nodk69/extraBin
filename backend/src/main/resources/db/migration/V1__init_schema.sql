-- 1. USERS TABLE
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(30) NOT NULL DEFAULT 'ROLE_USER',
    email_verified BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_users_username UNIQUE (username),
    CONSTRAINT uq_users_email UNIQUE (email)
);

CREATE INDEX idx_users_email_lower ON users (email);

-- 2. PASTES TABLE
CREATE TABLE pastes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id VARCHAR(16) NOT NULL,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    title VARCHAR(100),
    content TEXT NOT NULL,
    language VARCHAR(50) NOT NULL DEFAULT 'plaintext',
    visibility VARCHAR(20) NOT NULL DEFAULT 'PUBLIC',
    content_size_bytes INTEGER NOT NULL,
    line_count INTEGER NOT NULL,
    deletion_capability_hash VARCHAR(128),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    expires_at TIMESTAMP WITH TIME ZONE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT uq_pastes_public_id UNIQUE (public_id),
    CONSTRAINT chk_pastes_visibility CHECK (visibility IN ('PUBLIC', 'UNLISTED', 'PRIVATE')),
    CONSTRAINT chk_pastes_size CHECK (content_size_bytes <= 1048576)
);

CREATE INDEX idx_pastes_public_discovery ON pastes (created_at DESC, visibility);
CREATE INDEX idx_pastes_user_lookup ON pastes (user_id, created_at DESC);
CREATE INDEX idx_pastes_expiration ON pastes (expires_at);

-- 3. PASTE REVISIONS TABLE
CREATE TABLE paste_revisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paste_id BIGINT NOT NULL REFERENCES pastes(id) ON DELETE CASCADE,
    version BIGINT NOT NULL,
    title VARCHAR(100),
    content TEXT NOT NULL,
    language VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_paste_revision_version UNIQUE (paste_id, version)
);

CREATE INDEX idx_paste_revisions_lookup ON paste_revisions (paste_id, version DESC);

-- 4. PASSWORD RESET TOKENS
CREATE TABLE password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash VARCHAR(128) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_password_reset_token UNIQUE (token_hash)
);

CREATE INDEX idx_pwd_reset_active ON password_reset_tokens (token_hash);

-- 5. EMAIL VERIFICATION TOKENS
CREATE TABLE email_verification_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash VARCHAR(128) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_email_verify_token UNIQUE (token_hash)
);

-- 6. AUDIT EVENTS
CREATE TABLE audit_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type VARCHAR(50) NOT NULL,
    principal VARCHAR(100),
    ip_address VARCHAR(45),
    target_resource VARCHAR(100),
    outcome VARCHAR(20) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_audit_events_created ON audit_events (created_at DESC);
