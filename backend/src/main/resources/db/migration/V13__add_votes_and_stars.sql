-- 1. ADD CACHED COUNTERS WITH NON-NEGATIVE INVARIANTS
ALTER TABLE pastes ADD COLUMN upvotes BIGINT NOT NULL DEFAULT 0;
ALTER TABLE pastes ADD COLUMN downvotes BIGINT NOT NULL DEFAULT 0;
ALTER TABLE pastes ADD COLUMN stars_count BIGINT NOT NULL DEFAULT 0;

ALTER TABLE pastes ADD CONSTRAINT chk_pastes_upvotes_nonneg CHECK (upvotes >= 0);
ALTER TABLE pastes ADD CONSTRAINT chk_pastes_downvotes_nonneg CHECK (downvotes >= 0);
ALTER TABLE pastes ADD CONSTRAINT chk_pastes_stars_nonneg CHECK (stars_count >= 0);

ALTER TABLE paste_comments ADD COLUMN upvotes BIGINT NOT NULL DEFAULT 0;
ALTER TABLE paste_comments ADD COLUMN downvotes BIGINT NOT NULL DEFAULT 0;

ALTER TABLE paste_comments ADD CONSTRAINT chk_comments_upvotes_nonneg CHECK (upvotes >= 0);
ALTER TABLE paste_comments ADD CONSTRAINT chk_comments_downvotes_nonneg CHECK (downvotes >= 0);

-- 2. CREATE PASTE_VOTES TABLE WITH STRICT XOR IDENTITY CONSTRAINT
CREATE TABLE paste_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paste_id BIGINT NOT NULL REFERENCES pastes(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    client_ip_hash VARCHAR(64),
    vote_type VARCHAR(10) NOT NULL, -- 'UP' or 'DOWN'
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_paste_vote_type CHECK (vote_type IN ('UP', 'DOWN')),
    CONSTRAINT chk_paste_vote_identity_xor CHECK (
        (user_id IS NOT NULL AND client_ip_hash IS NULL) OR
        (user_id IS NULL AND client_ip_hash IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_paste_votes_user ON paste_votes (paste_id, user_id);
CREATE UNIQUE INDEX uq_paste_votes_ip ON paste_votes (paste_id, client_ip_hash);
CREATE INDEX idx_paste_votes_paste ON paste_votes (paste_id);

-- 3. CREATE PASTE_STARS TABLE
CREATE TABLE paste_stars (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paste_id BIGINT NOT NULL REFERENCES pastes(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uq_paste_stars_paste_user ON paste_stars (paste_id, user_id);
CREATE INDEX idx_paste_stars_user ON paste_stars (user_id);
CREATE INDEX idx_paste_stars_paste ON paste_stars (paste_id);

-- 4. CREATE PASTE_COMMENT_VOTES TABLE WITH STRICT XOR IDENTITY CONSTRAINT
CREATE TABLE paste_comment_votes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    comment_id BIGINT NOT NULL REFERENCES paste_comments(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    client_ip_hash VARCHAR(64),
    vote_type VARCHAR(10) NOT NULL, -- 'UP' or 'DOWN'
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_comment_vote_type CHECK (vote_type IN ('UP', 'DOWN')),
    CONSTRAINT chk_comment_vote_identity_xor CHECK (
        (user_id IS NOT NULL AND client_ip_hash IS NULL) OR
        (user_id IS NULL AND client_ip_hash IS NOT NULL)
    )
);

CREATE UNIQUE INDEX uq_comment_votes_user ON paste_comment_votes (comment_id, user_id);
CREATE UNIQUE INDEX uq_comment_votes_ip ON paste_comment_votes (comment_id, client_ip_hash);
CREATE INDEX idx_comment_votes_comment ON paste_comment_votes (comment_id);
