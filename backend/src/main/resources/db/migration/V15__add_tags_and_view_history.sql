-- =========================================================================

-- 1. TAGS TABLE (per-user normalized tag pool)
CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_tags_user_name UNIQUE (user_id, name)
);

CREATE INDEX idx_tags_user ON tags (user_id);

-- 2. PASTE_TAGS JOIN TABLE (many-to-many paste <-> tag)
CREATE TABLE paste_tags (
    paste_id BIGINT NOT NULL REFERENCES pastes(id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
    CONSTRAINT pk_paste_tags PRIMARY KEY (paste_id, tag_id)
);

CREATE INDEX idx_paste_tags_tag ON paste_tags (tag_id);

-- 3. PASTE_VIEW_HISTORY (per-user recently-viewed tracking)
CREATE TABLE paste_view_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    paste_id BIGINT NOT NULL REFERENCES pastes(id) ON DELETE CASCADE,
    viewed_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_view_history_user_paste UNIQUE (user_id, paste_id)
);

CREATE INDEX idx_view_history_user_time ON paste_view_history (user_id, viewed_at DESC);

-- 4. LAST_EDITED_AT (set only by the content-edit path; drives the recently-edited ledger
--    without conflating same-millisecond create+edit or share-link management with edits)
ALTER TABLE pastes ADD COLUMN last_edited_at TIMESTAMP WITH TIME ZONE;
