-- 1. CREATE REPLIES TABLE
CREATE TABLE replies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paste_id BIGINT NOT NULL REFERENCES pastes(id) ON DELETE CASCADE,
    parent_reply_id BIGINT REFERENCES replies(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    content TEXT NOT NULL,
    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_replies_paste_created ON replies (paste_id, created_at ASC);
CREATE INDEX idx_replies_parent ON replies (parent_reply_id);
CREATE INDEX idx_replies_author ON replies (author_id);

-- 2. CREATE NOTIFICATIONS TABLE
CREATE TABLE notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    actor_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    paste_id BIGINT NOT NULL REFERENCES pastes(id) ON DELETE CASCADE,
    reply_id BIGINT REFERENCES replies(id) ON DELETE CASCADE,
    type VARCHAR(50) NOT NULL,
    message VARCHAR(255) NOT NULL,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_notifications_recipient_created ON notifications (recipient_id, created_at DESC);
CREATE INDEX idx_notifications_recipient_unread ON notifications (recipient_id, is_read);

-- 3. USER NOTIFICATION PREFERENCES
ALTER TABLE users ADD COLUMN notify_on_replies BOOLEAN NOT NULL DEFAULT TRUE;
