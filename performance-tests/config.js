// ──────────────────────────────────────────────────────────────────────────────
// CSRF Token Helper
// ──────────────────────────────────────────────────────────────────────────────
// ExtraBin employs CookieCsrfTokenRepository with an X-XSRF-TOKEN header check.
// This helper issues a lightweight probe if needed to obtain the XSRF-TOKEN cookie
// and returns the necessary HTTP headers for state-mutating requests (POST/PUT/DELETE).
import http from 'k6/http';

export function getCsrfHeaders() {
  const probeRes = http.get(`${API_BASE}/pastes/probe-csrf-init`, {
    tags: { name: 'csrf_probe' },
  });

  let token = '';
  // Check response cookies or default jar cookies for current URL
  if (probeRes.cookies && probeRes.cookies['XSRF-TOKEN'] && probeRes.cookies['XSRF-TOKEN'].length > 0) {
    token = probeRes.cookies['XSRF-TOKEN'][0].value;
  }
  if (!token) {
    const jar = http.cookieJar();
    const cookies = jar.cookiesForURL(`${API_BASE}/pastes`);
    if (cookies && cookies['XSRF-TOKEN'] && cookies['XSRF-TOKEN'].length > 0) {
      token = cookies['XSRF-TOKEN'][0];
    }
  }

  return {
    'Content-Type': 'application/json',
    'Accept': 'application/json',
    'X-XSRF-TOKEN': token,
  };
}
